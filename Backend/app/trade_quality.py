"""Trade Quality Score (v7.11) — pure scoring function.

Wraps the per-(strategy × symbol × hour) edge data produced by
``scripts/build_edge_lookup.py`` into a 0-100 score and a tier
override for any single matched setup.

Pure metadata: this module never gates ``Strategy.matches()`` or
the backtest trade set. It is consumed by:
  * ``app/analyzer.py`` — to decorate ``matched_strategies`` output
    with ``tier``, ``score``, ``reasons``, and ``post_friction_avg_r``.
  * The ``/scan`` endpoint via ``app/schemas.py::SetupSignal`` — same
    decoration on CSV-upload responses.
  * ``app/autotrade.py`` (future, v7.12+) — to gate auto-fire on tier.

Design principles:
  * **Tier floor, not ceiling.** ``Strategy.tier`` (from
    ``app/strategies.py``) is the audit-locked classification. The
    score function may DEMOTE per-(symbol, hour) cell but never
    promote above the base tier. A bad symbol cell on an A-tier
    strategy becomes B-tier; a bad symbol cell on a B-tier strategy
    can become suppress.
  * **Reasons array is user-facing.** Each scored match carries a
    short list of plain-English reasons the score landed where it
    did — surfaced as a hover tooltip in the frontend and quoted
    by Sonnet in its analysis text.
  * **No I/O at score time.** The edge lookup is loaded once at
    module import (or via dependency-injection in tests). No file
    reads, no network, no Sonnet calls in this module.
"""
from __future__ import annotations

import json
import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger(__name__)

# ── Paths & loading ───────────────────────────────────────────────────────

_BACKEND_DIR = Path(__file__).resolve().parent.parent
DEFAULT_EDGE_LOOKUP_PATH = _BACKEND_DIR / "data" / "edge_lookup_v710.json"

# Friction level used in the lookup. Surfaced for clarity in the
# reasons strings; the JSON itself records ``_meta.friction_per_trade_r``.
DEFAULT_FRICTION_R = 0.10

# Minimum n required before a per-(symbol, hour) cell carries
# signal weight. Below this it's noise — fall back to the strategy
# aggregate.
_MIN_CELL_N = 5

# ── Score weights ─────────────────────────────────────────────────────────
# Sum to 1.0. Friction-weighted (strategy + symbol + hour) carries
# the bulk of the signal because the v7.10.5 audit showed friction
# is the dominant factor at our scale. MFE/MAE and volume are
# tiebreakers.
_W_STRATEGY_RAW       = 0.20
_W_STRATEGY_FRICTION  = 0.30
_W_SYMBOL_FRICTION    = 0.20
_W_HOUR_FRICTION      = 0.15
_W_MFE_OVER_MAE       = 0.10
_W_VOLUME_BOOST       = 0.05
assert abs(
    _W_STRATEGY_RAW + _W_STRATEGY_FRICTION + _W_SYMBOL_FRICTION
    + _W_HOUR_FRICTION + _W_MFE_OVER_MAE + _W_VOLUME_BOOST - 1.0
) < 1e-9

# Tier-demotion thresholds. Applied AFTER the score is computed —
# the demotion logic compares the (symbol, hour) cell's friction AvgR
# against these thresholds.
_DEMOTE_A_TO_B_FRICTION_AVG = 0.0     # A cell with negative friction
                                       # AvgR drops to B
_DEMOTE_B_TO_SUPPRESS_FRICTION_AVG = -0.30   # B cell badly negative
                                              # → suppress

# Score component normalization: AvgR values are squashed into [0, 1]
# via a logistic-like map. _SCORE_AVG_HALF is the AvgR at which the
# component returns 0.5; +1.0 AvgR is "very strong", -1.0 is "very
# weak". This is calibration, not a fundamental constant — adjust
# if score distributions look skewed in production.
_SCORE_AVG_HALF = 0.5    # AvgR=+0.5 maps to 0.5 score; AvgR=0 maps to ~0
_SCORE_AVG_RANGE = 1.0   # full range of meaningful AvgR


# ── Edge-lookup cache ─────────────────────────────────────────────────────

_edge_lookup_cache: dict | None = None


def load_edge_lookup(path: Path | None = None) -> dict:
    """Load the edge-lookup JSON (cached on first call).

    The JSON is committed to ``data/edge_lookup_v710.json`` and
    regenerated by ``scripts/build_edge_lookup.py``. Future versions
    (v7.12+) may swap in an updated JSON via the ``path`` arg.
    """
    global _edge_lookup_cache
    if path is not None:
        # Bypass cache for explicit-path loads (used by tests).
        with path.open() as f:
            return json.load(f)
    if _edge_lookup_cache is None:
        try:
            with DEFAULT_EDGE_LOOKUP_PATH.open() as f:
                _edge_lookup_cache = json.load(f)
        except FileNotFoundError:
            logger.warning(
                "edge_lookup_missing path=%s — score() will fall back to "
                "tier-only output until the JSON is regenerated.",
                DEFAULT_EDGE_LOOKUP_PATH,
            )
            _edge_lookup_cache = {}
    return _edge_lookup_cache


# ── Score function ────────────────────────────────────────────────────────

def _avg_r_to_unit(avg_r: float) -> float:
    """Map an AvgR value to [0, 1] for score blending.

    AvgR=0    → 0.50  (neutral)
    AvgR=+0.5 → 0.75
    AvgR=+1.0 → 1.00 (clipped)
    AvgR=-0.5 → 0.25
    AvgR=-1.0 → 0.00 (clipped)
    """
    unit = 0.5 + (avg_r / (2.0 * _SCORE_AVG_RANGE))
    return max(0.0, min(1.0, unit))


def score(
    strategy_name: str,
    symbol: str | None,
    rth_hour_et: int | None,
    ind: dict | None,
    edge_lookup: dict | None = None,
    base_tier: str = "B",
) -> dict:
    """Score a single matched setup.

    Args:
        strategy_name:  Exact ``Strategy.name`` (e.g. "ICT Power of 3 (Long)").
        symbol:         Ticker symbol (e.g. "AAPL"); None falls back to
                        strategy aggregate.
        rth_hour_et:    Local ET hour-of-day (0-23) for the entry bar;
                        None falls back to strategy aggregate.
        ind:            Live indicators dict (for vol_ratio, MFE/MAE
                        gates if present). May be None.
        edge_lookup:    Optional injection point for tests; defaults
                        to the cached JSON.
        base_tier:      The strategy's audit-locked tier from
                        ``Strategy.tier``. Score CAN demote below
                        this but never promote above it.

    Returns:
        Dict with keys:
          score:   int in [0, 100]
          tier:    "A" | "B" | "context" | "suppress"
          reasons: list[str] — 2-4 short lines of explanation
          post_friction_avg_r: float (best available estimate for
                               the live cell; cell-specific if
                               n >= _MIN_CELL_N, else strategy
                               aggregate)
    """
    if edge_lookup is None:
        edge_lookup = load_edge_lookup()

    reasons: list[str] = []
    strat_data = edge_lookup.get(strategy_name)
    if strat_data is None:
        # Strategy isn't in the lookup (could be a research-only
        # entry that hasn't been backtested). Return tier-only.
        return {
            "score": 50,
            "tier": base_tier,
            "reasons": [f"No backtest data for {strategy_name}; tier from playbook only."],
            "post_friction_avg_r": None,
        }

    # Strategy-level numbers
    strat_raw_avg = float(strat_data.get("raw_avg_r", 0.0))
    strat_fric_avg = float(strat_data.get("friction_avg_r", 0.0))
    strat_n = int(strat_data.get("n", 0))
    reasons.append(
        f"Strategy 18m: n={strat_n}, raw AvgR {strat_raw_avg:+.3f}, "
        f"after-friction {strat_fric_avg:+.3f}"
    )

    # Symbol cell
    sym_data = (strat_data.get("by_symbol") or {}).get(symbol) if symbol else None
    if sym_data and int(sym_data.get("n", 0)) >= _MIN_CELL_N:
        sym_fric_avg = float(sym_data["friction_avg_r"])
        sym_n = int(sym_data["n"])
        reasons.append(
            f"Symbol {symbol}: n={sym_n}, after-friction {sym_fric_avg:+.3f}"
        )
        post_friction_avg_r = sym_fric_avg
    else:
        sym_fric_avg = strat_fric_avg
        if symbol and sym_data:
            reasons.append(f"Symbol {symbol}: n<{_MIN_CELL_N} (using strategy aggregate)")
        post_friction_avg_r = strat_fric_avg

    # Hour cell
    hour_key = str(rth_hour_et) if rth_hour_et is not None else None
    hour_data = (strat_data.get("by_hour") or {}).get(hour_key) if hour_key else None
    if hour_data and int(hour_data.get("n", 0)) >= _MIN_CELL_N:
        hour_fric_avg = float(hour_data["friction_avg_r"])
        hour_n = int(hour_data["n"])
        reasons.append(
            f"Hour {rth_hour_et:02d}:00 ET: n={hour_n}, "
            f"after-friction {hour_fric_avg:+.3f}"
        )
    else:
        hour_fric_avg = strat_fric_avg

    # MFE-over-MAE and volume-confirmation come from the live ``ind``
    # — these are CURRENT-bar gates, not historical edge. We give
    # them small weight because they're noisy on a single bar.
    ind = ind or {}
    mfe = ind.get("mfe_r")
    mae = ind.get("mae_r")
    if mfe is not None and mae is not None and mae > 0:
        mfe_over_mae_unit = max(0.0, min(1.0, float(mfe) / float(mae) / 2.0))
    else:
        mfe_over_mae_unit = 0.5  # neutral when we can't compute
    vol_ratio = ind.get("vol_ratio")
    if vol_ratio is not None:
        # Neutral=0.5 at vol_ratio=1.0; saturates ~0.75 at 1.5x; ~0.25 at 0.5x.
        vol_unit = max(0.0, min(1.0, 0.25 + 0.5 * float(vol_ratio)))
    else:
        vol_unit = 0.5

    # Score blend (each component in [0, 1], weighted-sum → [0, 1] → ×100)
    blended = (
        _W_STRATEGY_RAW       * _avg_r_to_unit(strat_raw_avg)
        + _W_STRATEGY_FRICTION  * _avg_r_to_unit(strat_fric_avg)
        + _W_SYMBOL_FRICTION    * _avg_r_to_unit(sym_fric_avg)
        + _W_HOUR_FRICTION      * _avg_r_to_unit(hour_fric_avg)
        + _W_MFE_OVER_MAE       * mfe_over_mae_unit
        + _W_VOLUME_BOOST       * vol_unit
    )
    score_int = int(round(blended * 100))

    # ── v7.12 catalyst/momentum boosts ─────────────────────────────────────
    # Small additive boosts that help RANK matches without overpowering
    # the post-friction edge anchor. Total catalyst contribution is
    # capped at +12 / 100 so a friction-negative cell can never reach
    # an A-grade-looking score by stacking boosts.
    #
    # Catalysts come from already-computed `ind` fields — no new data
    # sources. Each is a tiebreaker, not a primary driver.
    catalyst_boost = 0
    catalyst_reasons: list[str] = []

    # 1. Daily relative volume (cumulative-vs-20-day-avg). High RVOL =
    # institutional interest; low RVOL = lackluster participation.
    rvol_vs_20d = ind.get("rvol_vs_20d")
    if rvol_vs_20d is not None:
        rvol = float(rvol_vs_20d)
        if rvol >= 1.5:
            catalyst_boost += 2
            catalyst_reasons.append(f"High RVOL ({rvol:.2f}× 20-day avg)")
        elif rvol < 0.7:
            catalyst_boost -= 2
            catalyst_reasons.append(f"Low RVOL ({rvol:.2f}× 20-day avg)")

    # 2. Liquidity stacking — count of S/R touches the bar is sitting on.
    # 3+ touches = confluence anchor. +1.5 per touch, max +6.
    touches_total = 0
    for k in ("touches_prev_high", "touches_prev_low",
              "touches_session_high", "touches_session_low"):
        v = ind.get(k)
        if v is not None:
            try:
                touches_total += int(v)
            except (TypeError, ValueError):
                pass
    if touches_total > 0:
        touch_boost = min(6, int(round(1.5 * touches_total)))
        catalyst_boost += touch_boost
        catalyst_reasons.append(
            f"Liquidity stacking: {touches_total} key-level touches (+{touch_boost})"
        )

    # 3. Multi-timeframe alignment — RSI + EMA both agreeing with
    # strategy direction. Strategy direction is implied by the name
    # (not passed in), so we read it from the strategy_name suffix.
    is_long_strategy = "(Long)" in strategy_name
    is_short_strategy = "(Short)" in strategy_name
    rsi_align = ind.get("rsi_alignment")
    ema_align = ind.get("ema_alignment_mtf")
    if rsi_align and ema_align and (is_long_strategy or is_short_strategy):
        long_aligned = (
            (str(rsi_align).lower() in ("all_oversold", "bullish", "long_aligned")
             or str(rsi_align).lower().startswith("long"))
            and (str(ema_align).lower() in ("bullish", "long_aligned", "price_above_emas")
                 or str(ema_align).lower().startswith("long"))
        )
        short_aligned = (
            (str(rsi_align).lower() in ("all_overbought", "bearish", "short_aligned")
             or str(rsi_align).lower().startswith("short"))
            and (str(ema_align).lower() in ("bearish", "short_aligned", "price_below_emas")
                 or str(ema_align).lower().startswith("short"))
        )
        if (is_long_strategy and long_aligned) or (is_short_strategy and short_aligned):
            catalyst_boost += 3
            catalyst_reasons.append("Multi-TF RSI + EMA aligned with strategy direction")

    # 4. Regime fit — surface in reasons only (no score change; regime
    # already weights confidence elsewhere via app/regime.py).
    regime = ind.get("regime")
    if regime and regime != "unknown":
        regime_aligned = (
            (is_long_strategy and regime == "trending_up")
            or (is_short_strategy and regime == "trending_down")
            or regime == "choppy"  # neutral — both sides ok
        )
        if regime_aligned:
            catalyst_reasons.append(f"Regime: {regime} (aligned)")
        else:
            catalyst_reasons.append(f"Regime: {regime} (against direction)")

    # Cap total catalyst contribution at ±12 to keep post-friction edge
    # as the dominant signal. A friction-negative cell maxing out the
    # catalyst boost still cannot reach an A-grade-looking score.
    catalyst_boost = max(-12, min(12, catalyst_boost))
    score_int = max(0, min(100, score_int + catalyst_boost))
    if catalyst_reasons:
        # Surface as a single bundled reason line so the reasons array
        # doesn't balloon for every tooltip render.
        sign = "+" if catalyst_boost >= 0 else "-"
        reasons.append(
            f"Catalyst {sign}{abs(catalyst_boost)}: " + "; ".join(catalyst_reasons)
        )

    # Tier decision
    tier = base_tier
    if base_tier == "A":
        # Demote A → B if either symbol or hour cell has negative
        # post-friction AvgR.
        if sym_fric_avg < _DEMOTE_A_TO_B_FRICTION_AVG or hour_fric_avg < _DEMOTE_A_TO_B_FRICTION_AVG:
            tier = "B"
            reasons.append("Demoted A → B (current symbol/hour cell post-friction negative)")
    elif base_tier == "B":
        # Demote B → suppress if BOTH symbol and hour cells are
        # badly negative. Single negative cell stays B.
        if (
            sym_fric_avg < _DEMOTE_B_TO_SUPPRESS_FRICTION_AVG
            and hour_fric_avg < _DEMOTE_B_TO_SUPPRESS_FRICTION_AVG
        ):
            tier = "suppress"
            reasons.append("Demoted B → suppress (both symbol and hour cells deeply negative)")
    # tier == "context" passes through untouched.

    return {
        "score": score_int,
        "tier": tier,
        "reasons": reasons,
        "post_friction_avg_r": round(float(post_friction_avg_r), 4),
    }
